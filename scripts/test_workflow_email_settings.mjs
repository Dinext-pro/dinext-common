import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const handlers = {};
const row = {doctype: 'Workflow Document State', name: 'row', state:'Rejected', send_email:1, custom_email_settings_override:0};
const frm = {doc: {custom_group_workflow_action_emails:1, custom_group_interval_unit:'Days', custom_group_interval_value:1, custom_group_send_times:'08:00, 17:00', custom_group_email_template:'Digest', custom_workflow_action_email_template:'Action', states:[row]}, refresh_field(){}, dirty(){this.dirtied=true;}};
const context = {frappe:{ui:{form:{on(dt,events){handlers[dt]={...handlers[dt],...events};}}}}, locals:{'Workflow Document State':{row}}, __:s=>s, console};
vm.runInNewContext(fs.readFileSync('dinext_common/public/js/workflow_email_settings.js','utf8'),context);
handlers.Workflow.refresh(frm);
assert.equal(row.custom_group_workflow_action_emails,1);
assert.equal(row.custom_email_settings_override,0);
assert.equal(frm.dirtied,undefined);
row.custom_group_workflow_action_emails=0;
handlers['Workflow Document State'].custom_group_workflow_action_emails(frm,row.doctype,row.name);
assert.equal(row.custom_email_settings_override,1);
assert.equal(row.custom_group_workflow_action_emails,0);
assert.equal(row.custom_group_send_times,'08:00, 17:00');
frm.doc.custom_group_send_times='10:00';
handlers.Workflow.custom_group_send_times(frm);
assert.equal(row.custom_group_send_times,'08:00, 17:00');
handlers['Workflow Document State'].custom_email_settings_reset(frm,row.doctype,row.name);
assert.equal(row.custom_email_settings_override,0);
assert.equal(row.custom_group_send_times,'10:00');
assert.equal(row.send_email,1);
console.log('Workflow email inheritance UI: 11 assertions passed');
